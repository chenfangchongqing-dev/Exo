/* Teacher-rule fallback for S09's existing Chinese argument and blocked French formulation.
   Rules are explicit: these responses are not generated by GLM. Other tasks use the live backend.
   The learner's first French sentence is sent to GLM for feedback and transfer. */
(function(root){
  "use strict";
  function mixed(s){
    return (s.match(/[\u3400-\u9fff]/g)||[]).length>=45 &&
      (s.match(/[A-Za-z\u00c0-\u024f]/g)||[]).length>=75;
  }
  function theme(s){
    return (/(?:r[ée]seaux sociaux|社交媒体|网上分享|网络分享)/i.test(s) &&
      /(?:酒店|h[ôo]tel|拼团|轮流拍照|模仿|高品质|奢华|luxueux|luxe|物质生活)/i.test(s)) ||
      /拼团.{0,16}酒店|轮流拍照/i.test(s);
  }
  function blocked(s){
    return /不知道.{0,6}法语.{0,10}(?:写|说|表达)|不会.{0,7}写法语|不会写法语|法语(?:句子)?写不出来|用法语(?:写|说)不出来|不知道怎么用法语|整段.{0,8}(?:翻译|法语)|je (?:ne )?sais pas (?:comment )?[ée]crire en fran[cç]ais|je bloque en fran[cç]ais|je n.arrive pas [àa] (?:l.)?[ée]crire en fran[cç]ais/i.test(s);
  }
  function firstDraft(s,history){
    if(mixed(s) && theme(s))return s;
    var earlier=(history||[]).filter(function(t){return t.role==="user"}).map(function(t){return t.text}).reverse();
    return earlier.find(function(t){return typeof t==="string" && mixed(t)&&theme(t)})||"";
  }
  function localSupport(input,history,meta){
    var s=String(input||"").trim();
    var draft=firstDraft(s,history);
    if(!draft || (!mixed(s) && !blocked(s)))return null;
    var m=meta||{};
    var support=m.difficulty==="language"?Number(m.support)||0:0;
    var zh=draft.match(/[\u3400-\u9fff][\s\S]{35,}/);
    var goal=(zh?zh[0]:draft).replace(/\s+/g," ").slice(0,190);
    var output;
    if(mixed(s)){
      output={
        reply:"你已经有法语开头和完整的中文构思。问题在语言表达，而不是缺少观点或例子。\n先拆成三层：①看到网络上更高品质的生活，引发向往；②拼团订豪华酒店、拍照模仿；③得到短暂满足。\n先表达第①层。可以尝试调用 « susciter l'envie de » 和 « un mode de vie luxueux »，自己写一句法语。",
        support:1,strategy:"meaning-split",next:"Essayer une phrase sur les réseaux sociaux"
      };
    } else if(support<2 && !/整段|全文|全部翻译/.test(s)){
      output={
        reply:"你刚才的中文已经说清楚意思，不需要再解释一遍。先借用这个法语句架：\n« Sur les réseaux sociaux, les images d'un mode de vie luxueux peuvent ... »\n要表达“引发向往”，可调用 « susciter l'envie de + infinitif »。请只补全这一句，不必整段翻译。",
        support:2,strategy:"sentence-frame",next:"Compléter une phrase avec susciter l'envie"
      };
    } else {
      output={
        reply:"如果句架仍然难以使用，我提供一句局部示范：\n« Les images de vies luxueuses sur les réseaux sociaux peuvent susciter l'envie de mener une vie semblable. »\n现在请迁移到你自己的酒店例子：选择 « imiter un mode de vie » 或 « donner l'impression de »，自己写第二句。写完后我们检查它是否忠于原意。",
        support:3,strategy:"bounded-model-and-transfer",next:"Réutiliser l'expression pour décrire l'hôtel"
      };
    }
    return {reply:output.reply,phase:"writing",language:"zh",meta:{
      goal:goal,task:"argumenter",difficulty:"language",support:output.support,
      stuck:0,next:output.next,lastStrategy:output.strategy,previousIntent:"language-scaffold-local"
    }};
  }
  root.COMPAGNON_S09_SUPPORT=localSupport;
  if(typeof module!=="undefined" && module.exports)module.exports=localSupport;
})(typeof window!=="undefined"?window:globalThis);
